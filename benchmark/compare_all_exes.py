def run_exe(exe, parfile, workdir, env, timeout=180):
    """Run a GSLIB exe, return (elapsed, returncode, stdout, stderr)."""
    t0 = time.perf_counter()
    try:
        proc = subprocess.run(
            [str(exe)], input=str(parfile) + "\n",
            capture_output=True, text=True,
            cwd=str(workdir), env=env, timeout=timeout
        )
        elapsed = time.perf_counter() - t0
        return elapsed, proc.returncode, proc.stdout, proc.stderr
    except subprocess.TimeoutExpired:
        return time.perf_counter() - t0, -1, "", "TIMEOUT"
    except Exception as e:
        return time.perf_counter() - t0, -99, "", str(e)


def read_gslib_numeric(filepath):
    """Read all numeric values from a GSLIB-format output file.

    Handles:
    - Standard GSLIB headers (title, ncols, var names, data)
    - Old format where ncols + grid dims are on one line
    - Fortran format overflow '**********' (treated as NaN/skipped)
    - Non-GSLIB files (just extract all numbers)
    """
    vals = []
    try:
        with open(filepath) as f:
            lines = f.readlines()
    except Exception:
        return vals

    if len(lines) < 3:
        # Too short for GSLIB header, just extract numbers
        for line in lines:
            _extract_numbers(line, vals)
        return vals

    # Try to parse GSLIB header
    # Line 0: title
    # Line 1: ncols (possibly followed by grid dims in old format)
    hdr = lines[1].strip().split()
    if not hdr:
        return vals

    try:
        ncols = int(hdr[0])
    except ValueError:
        # Not a GSLIB file, just extract all numbers
        for line in lines:
            _extract_numbers(line, vals)
        return vals

    # Sanity check: ncols should be reasonable (1-200)
    if ncols < 1 or ncols > 200:
        for line in lines:
            _extract_numbers(line, vals)
        return vals

    # Skip header: title (1) + ncols line (1) + var names (ncols)
    data_start = 2 + ncols

    # Verify: the lines after ncols line should look like variable names
    # (not pure numbers). If they look numeric, header parsing is wrong.
    if data_start <= len(lines):
        for line in lines[data_start:]:
            _extract_numbers(line, vals)

    return vals


def _extract_numbers(line, vals):
    """Extract numeric values from a line, handling '**********' overflow."""
    parts = line.strip().split()
    for p in parts:
        if '*' in p and len(p) > 1 and p.replace('*', '') == '':
            # Fortran format overflow: e.g. '**********'
            # Use a sentinel NaN-like value
            vals.append(float('inf'))
            continue
        try:
            vals.append(float(p))
        except ValueError:
            continue


def compare_outputs(dir_a, dir_b, output_files, label_a, label_b, prog):
    """Compare output files between two runs. Return comparison list."""
    results = []
    for outf in output_files:
        f_a = dir_a / outf
        f_b = dir_b / outf
        if not f_a.exists() and not f_b.exists():
            results.append((outf, "BOTH_MISSING", ""))
            continue
        if not f_a.exists():
            results.append((outf, "MISSING_A", f"{label_a} missing"))
            continue
        if not f_b.exists():
            results.append((outf, "MISSING_B", f"{label_b} missing"))
            continue

        v_a = read_gslib_numeric(f_a)
        v_b = read_gslib_numeric(f_b)

        if not v_a and not v_b:
            sz_a = f_a.stat().st_size
            sz_b = f_b.stat().st_size
            results.append((outf, "EMPTY", f"sizes: {sz_a} vs {sz_b}"))
            continue

        if not v_a or not v_b:
            results.append((outf, "ONE_EMPTY",
                f"a={len(v_a)} vals, b={len(v_b)} vals"))
            continue

        # Filter out inf values (from '**********' overflow) from both
        paired = []
        inf_a = sum(1 for v in v_a if v == float('inf'))
        inf_b = sum(1 for v in v_b if v == float('inf'))

        if len(v_a) != len(v_b):
            detail = f"n={len(v_a)} vs {len(v_b)}"
            if inf_a or inf_b:
                detail += f" (overflow: a={inf_a}, b={inf_b})"
            # Still compare up to min length, excluding inf
            n = min(len(v_a), len(v_b))
            for i in range(n):
                if v_a[i] != float('inf') and v_b[i] != float('inf'):
                    paired.append((v_a[i], v_b[i]))
            if not paired:
                results.append((outf, "COUNT_DIFF", detail))
                continue
            # Compute diffs on paired values
            diffs = [abs(a - b) for a, b in paired]
            max_diff = max(diffs)
            if max_diff == 0:
                results.append((outf, "COUNT_DIFF_BUT_MATCH", detail + f", paired={len(paired)} all exact"))
            elif max_diff < 0.01:
                results.append((outf, "COUNT_DIFF_CLOSE", detail + f", paired={len(paired)} max_diff={max_diff:.2e}"))
            else:
                results.append((outf, "COUNT_DIFF", detail + f", paired={len(paired)} max_diff={max_diff:.2e}"))
            continue

        n = len(v_a)
        # Filter out matching inf pairs
        for i in range(n):
            if v_a[i] == float('inf') and v_b[i] == float('inf'):
                continue  # both overflow, skip
            if v_a[i] == float('inf') or v_b[i] == float('inf'):
                paired.append((v_a[i], v_b[i]))  # one overflow, flag it
            else:
                paired.append((v_a[i], v_b[i]))

        if not paired:
            results.append((outf, "ALL_OVERFLOW", f"n={n}"))
            continue

        # Check for inf mismatches
        inf_mismatches = sum(1 for a, b in paired
                           if (a == float('inf')) != (b == float('inf')))
        finite_pairs = [(a, b) for a, b in paired
                       if a != float('inf') and b != float('inf')]

        if not finite_pairs:
            if inf_mismatches:
                results.append((outf, "OVERFLOW_MISMATCH", f"n={n}, inf_mismatches={inf_mismatches}"))
            else:
                results.append((outf, "ALL_OVERFLOW", f"n={n}"))
            continue

        diffs = [abs(a - b) for a, b in finite_pairs]
        max_diff = max(diffs)
        mean_diff = sum(diffs) / len(diffs)
        exact = sum(1 for d in diffs if d == 0.0)
        np = len(finite_pairs)

        extra = ""
        if inf_mismatches:
            extra = f", overflow_mismatch={inf_mismatches}"

        if max_diff == 0 and not inf_mismatches:
            status = "IDENTICAL"
            detail = f"n={np}"
        elif max_diff < 0.0001 and not inf_mismatches:
            status = "MATCH_4DP"
            detail = f"n={np}, max_diff={max_diff:.2e}{extra}"
        elif max_diff < 0.01 and not inf_mismatches:
            status = "MATCH_2DP"
            detail = f"n={np}, max_diff={max_diff:.2e}, exact={exact}/{np}{extra}"
        elif max_diff < 1.0:
            status = "CLOSE"
            detail = f"n={np}, max_diff={max_diff:.4f}, mean_diff={mean_diff:.4f}{extra}"
        else:
            status = "DIFFERS"
            mean_a = sum(a for a, b in finite_pairs) / np
            mean_b = sum(b for a, b in finite_pairs) / np
            detail = f"n={np}, max_diff={max_diff:.4f}, mean_a={mean_a:.4f}, mean_b={mean_b:.4f}{extra}"

        results.append((outf, status, detail))

    return results


def test_program(prog, parfile, output_files):
    """Run one program across all available sources, compare outputs."""
    results = {"prog": prog}

    # Find which sources have this exe
    available = {}
    for src_label, src_dir in SOURCES.items():
        aliases = EXE_ALIASES.get(prog, {})
        exe_name = aliases.get(src_label, prog)
        if exe_name is None:
            continue
        exe = src_dir / f"{exe_name}.exe"
        if exe.exists():
            available[src_label] = exe

    if not available:
        results["status"] = "NO_EXES"
        return results
    if "bin_opt" not in available:
        results["status"] = "NO_OPT"
        return results

    # If this program needs input from another program, generate it first
    # using bin_opt, then copy to all workdirs
    generated_input = None
    if prog in NEEDS_INPUT:
        gen_prog, gen_par, gen_file = NEEDS_INPUT[prog]
        gen_exe = SOURCES["bin_opt"] / f"{gen_prog}.exe"
        if gen_exe.exists():
            gen_workdir = BASE / f"{prog}_gen_input"
            setup_workdir(gen_prog, "bin_opt", gen_workdir)
            run_exe(gen_exe, gen_par, gen_workdir, ENV_NEW)
            gen_output = gen_workdir / gen_file
            if gen_output.exists():
                generated_input = gen_output

    # Run each version
    run_results = {}
    for src_label, exe in available.items():
        workdir = BASE / f"{prog}_{src_label}"
        setup_workdir(prog, src_label, workdir)
        # Copy generated input file into workdir if needed
        if generated_input and generated_input.exists():
            shutil.copy2(generated_input, workdir / generated_input.name)
        env = ENV_NEW if src_label in ("bin_opt", "gslib2") else ENV_OLD
        # Use version-specific par file if needed
        use_par = parfile
        if src_label == "gslib_ori" and prog in OLD_PAR_FILES:
            use_par = OLD_PAR_FILES[prog]
        elif src_label in ("bin_opt", "gslib2") and prog in NEW_PAR_FILES:
            use_par = NEW_PAR_FILES[prog]
        elapsed, rc, stdout, stderr = run_exe(exe, use_par, workdir, env)
        run_results[src_label] = {
            "elapsed": elapsed, "rc": rc, "workdir": workdir,
            "stdout": stdout[:500], "stderr": stderr[:500]
        }

    results["runs"] = run_results

    # Compare each old source against bin_opt
    comparisons = {}
    opt_dir = run_results["bin_opt"]["workdir"]
    for src_label in available:
        if src_label == "bin_opt":
            continue
        old_dir = run_results[src_label]["workdir"]
        old_rc = run_results[src_label]["rc"]
        new_rc = run_results["bin_opt"]["rc"]

        if old_rc != 0 or new_rc != 0:
            detail = f"old_rc={old_rc} new_rc={new_rc}"
            if old_rc != 0:
                detail += f" old_stderr={run_results[src_label]['stderr'][:100]}"
            if new_rc != 0:
                detail += f" new_stderr={run_results['bin_opt']['stderr'][:100]}"
            comparisons[src_label] = [("*", "RUN_FAILED", detail)]
            continue

        if output_files:
            comparisons[src_label] = compare_outputs(
                old_dir, opt_dir, output_files, src_label, "bin_opt", prog)
        else:
            comparisons[src_label] = [("*", "NO_OUTPUT_FILES", "")]

    results["comparisons"] = comparisons
    return results


